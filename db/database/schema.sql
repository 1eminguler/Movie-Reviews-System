-- =====================================================================
-- Movie Reviews System: veritabanı şeması (PostgreSQL)
-- =====================================================================


-- ---------------------------------------------------------------------
-- users: kullanıcılar
-- ---------------------------------------------------------------------
CREATE TABLE users (
  id            INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  username      VARCHAR(50)  NOT NULL UNIQUE,
  email         VARCHAR(255) NOT NULL UNIQUE,
  password_hash VARCHAR(255) NOT NULL,
  created_at    TIMESTAMPTZ  NOT NULL DEFAULT now()
);



-- ---------------------------------------------------------------------
-- genres: türler (TMDB'den 18 tür gelecek, TV Movie hariç)
-- ---------------------------------------------------------------------
CREATE TABLE genres (
  id            INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  tmdb_genre_id INTEGER      NOT NULL UNIQUE,
  name          VARCHAR(100) NOT NULL
);


-- ---------------------------------------------------------------------
-- directors: yönetmenler
-- ---------------------------------------------------------------------
CREATE TABLE directors (
  id             INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  tmdb_person_id INTEGER      NOT NULL UNIQUE,
  name           VARCHAR(255) NOT NULL
);



-- ---------------------------------------------------------------------
-- movies: filmler (TMDB'den gelen veri + bizim kullanıcı puanlarımızın özeti)
-- ---------------------------------------------------------------------
CREATE TABLE movies (
  id                INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  tmdb_id           INTEGER      NOT NULL UNIQUE,
  title             VARCHAR(255) NOT NULL,
  original_title    VARCHAR(255),
  original_language VARCHAR(10),
  release_date      DATE,
  overview          TEXT,
  runtime           SMALLINT,
  poster_path       VARCHAR(255),
  backdrop_path     VARCHAR(255),
  certification     VARCHAR(5)
                    CHECK (certification IN ('G', 'PG', 'PG-13', 'R', 'NC-17')),
  avg_rating        NUMERIC(3,2)
                    CHECK (avg_rating BETWEEN 1 AND 5),
  review_count      INTEGER      NOT NULL DEFAULT 0
                    CHECK (review_count >= 0),
  created_at        TIMESTAMPTZ  NOT NULL DEFAULT now()
);



-- ---------------------------------------------------------------------
-- movie_genres: film-tür ilişkisi (bir filmin birden çok türü olabilir)
-- ---------------------------------------------------------------------
CREATE TABLE movie_genres (
  movie_id INTEGER NOT NULL REFERENCES movies(id) ON DELETE CASCADE,
  genre_id INTEGER NOT NULL REFERENCES genres(id) ON DELETE CASCADE,
  PRIMARY KEY (movie_id, genre_id)
);


-- ---------------------------------------------------------------------
-- movie_directors: film-yönetmen ilişkisi (birden çok yönetmen olabilir;
-- yönetmeni bilinmeyen filmin bu tabloda satırı olmaz)
-- ---------------------------------------------------------------------
CREATE TABLE movie_directors (
  movie_id    INTEGER NOT NULL REFERENCES movies(id)    ON DELETE CASCADE,
  director_id INTEGER NOT NULL REFERENCES directors(id) ON DELETE CASCADE,
  PRIMARY KEY (movie_id, director_id)
);



-- ---------------------------------------------------------------------
-- reviews: kullanıcı puanları ve yorumları + duygu analizi sonucu
-- ---------------------------------------------------------------------
CREATE TABLE reviews (
  id               INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  movie_id         INTEGER     NOT NULL REFERENCES movies(id) ON DELETE CASCADE,
  user_id          INTEGER     NOT NULL REFERENCES users(id)  ON DELETE CASCADE,
  rating           SMALLINT    NOT NULL CHECK (rating BETWEEN 1 AND 5),
  review_text      TEXT        CHECK (review_text IS NULL OR length(btrim(review_text)) > 0),
  sentiment_label  VARCHAR(10) CHECK (sentiment_label IN ('positive', 'negative', 'neutral')),
  sentiment_score  NUMERIC(3,2) CHECK (sentiment_score BETWEEN 0 AND 1),
  sentiment_status VARCHAR(10) NOT NULL DEFAULT 'pending'
                   CHECK (sentiment_status IN ('pending', 'done', 'failed', 'skipped')),
  created_at       TIMESTAMPTZ NOT NULL DEFAULT now(),
  updated_at       TIMESTAMPTZ NOT NULL DEFAULT now(),

  -- Bir kullanıcı bir filme yalnızca bir yorum yazabilir
  UNIQUE (user_id, movie_id),

  -- Etiket ve skor birlikte dolu ya da birlikte boş olmalı
  CHECK ((sentiment_label IS NULL) = (sentiment_score IS NULL)),

  -- Durum 'done' ise sonuç mutlaka yazılmış olmalı
  CHECK (sentiment_status <> 'done' OR sentiment_label IS NOT NULL)
);



-- =====================================================================
-- İNDEKSLER (filtreleme, sıralama ve arama performansı için)
-- =====================================================================

-- Başlık araması (ILIKE '%kelime%') için: pg_trgm uzantısı
CREATE EXTENSION IF NOT EXISTS pg_trgm;
CREATE INDEX idx_movies_title_trgm ON movies USING gin (title gin_trgm_ops);

-- Film listesi filtreleri ve sıralamaları
CREATE INDEX idx_movies_release_date      ON movies (release_date);
CREATE INDEX idx_movies_avg_rating        ON movies (avg_rating DESC NULLS LAST);
CREATE INDEX idx_movies_runtime           ON movies (runtime);
CREATE INDEX idx_movies_original_language ON movies (original_language);

-- Tür ve yönetmene göre filtre (bağlantı tablolarında "tersten" arama)
CREATE INDEX idx_movie_genres_genre_id        ON movie_genres (genre_id);
CREATE INDEX idx_movie_directors_director_id  ON movie_directors (director_id);

-- Bir filmin yorumlarını getirme
CREATE INDEX idx_reviews_movie_id ON reviews (movie_id);

-- Duygu analizi bekleyen yorumları hızlı bulma (sadece pending satırları indeksler)
CREATE INDEX idx_reviews_pending_sentiment ON reviews (created_at)
  WHERE sentiment_status = 'pending';



-- =====================================================================
-- TRIGGER: film ortalama puanı ve yorum sayısı otomatik güncellenir
-- avg_rating ve review_count kolonlarını elle GÜNCELLEMEYİN!
-- =====================================================================

-- Bir filmin yorum sayısını ve ortalamasını yeniden hesaplar
CREATE OR REPLACE FUNCTION refresh_movie_rating(p_movie_id INTEGER)
RETURNS void AS $$
BEGIN
  -- Film satırını kilitle: aynı anda gelen iki yorum sırayla işlenir,
  -- böylece biri diğerinin sonucunu ezmez
  PERFORM 1 FROM movies WHERE id = p_movie_id FOR UPDATE;

  UPDATE movies m
  SET review_count = s.cnt,
      avg_rating   = s.avg_r
  FROM (
    SELECT COUNT(*)::int AS cnt, ROUND(AVG(rating), 2) AS avg_r
    FROM reviews
    WHERE movie_id = p_movie_id
  ) s
  WHERE m.id = p_movie_id;
END;
$$ LANGUAGE plpgsql SET search_path = public;


-- Hangi olayda hangi filmin yenileneceğini belirler
CREATE OR REPLACE FUNCTION trg_reviews_update_movie_rating()
RETURNS trigger AS $$
BEGIN
  IF TG_OP = 'DELETE' THEN
    PERFORM refresh_movie_rating(OLD.movie_id);
  ELSE
    PERFORM refresh_movie_rating(NEW.movie_id);
    -- Yorum başka bir filme taşındıysa eski filmi de yenile
    IF TG_OP = 'UPDATE' AND OLD.movie_id <> NEW.movie_id THEN
      PERFORM refresh_movie_rating(OLD.movie_id);
    END IF;
  END IF;
  RETURN NULL;
END;
$$ LANGUAGE plpgsql SET search_path = public;


CREATE TRIGGER trg_reviews_rating_sync
AFTER INSERT OR DELETE OR UPDATE OF rating, movie_id ON reviews
FOR EACH ROW EXECUTE FUNCTION trg_reviews_update_movie_rating();



-- =====================================================================
-- TRIGGER: yorum yazılırken duygu durumu ve updated_at otomatik ayarlanır
--  * Metni olmayan yorum 'skipped' olur (LLM'e gönderilecek bir şey yok)
--  * Yorum metni değişirse eski duygu sonucu silinir, durum yeniden
--    'pending' olur (metin silindiyse 'skipped')
--  * updated_at yalnızca puan veya metin değişince yenilenir
--    (duygu sonucu yazmak updated_at'i değiştirmez)
-- =====================================================================
CREATE OR REPLACE FUNCTION trg_reviews_before_write()
RETURNS trigger AS $$
BEGIN
  IF TG_OP = 'INSERT' THEN
    IF NEW.review_text IS NULL THEN
      NEW.sentiment_status := 'skipped';
      NEW.sentiment_label  := NULL;
      NEW.sentiment_score  := NULL;
    END IF;

  ELSIF TG_OP = 'UPDATE' THEN
    IF NEW.rating IS DISTINCT FROM OLD.rating
       OR NEW.review_text IS DISTINCT FROM OLD.review_text THEN
      NEW.updated_at := now();
    END IF;

    IF NEW.review_text IS DISTINCT FROM OLD.review_text THEN
      NEW.sentiment_label := NULL;
      NEW.sentiment_score := NULL;
      NEW.sentiment_status :=
        CASE WHEN NEW.review_text IS NULL THEN 'skipped' ELSE 'pending' END;
    END IF;
  END IF;

  RETURN NEW;
END;
$$ LANGUAGE plpgsql SET search_path = public;


CREATE TRIGGER trg_reviews_before_write
BEFORE INSERT OR UPDATE ON reviews
FOR EACH ROW EXECUTE FUNCTION trg_reviews_before_write();



-- =====================================================================
-- VIEW: movie_details
-- Film listesi/detayı için hazır sorgu: her film TEK satırdır.
-- Türler ve yönetmenler dizi olarak gelir (yönetmeni olmayan filmde boş dizi).
--   genre_ids / genre_names       aynı sıradadır (ada göre sıralı)
--   director_ids / director_names aynı sıradadır (ada göre sıralı)
-- =====================================================================
CREATE VIEW movie_details AS
SELECT
  m.id,
  m.tmdb_id,
  m.title,
  m.original_title,
  m.original_language,
  m.release_date,
  m.overview,
  m.runtime,
  m.poster_path,
  m.certification,
  m.avg_rating,
  m.review_count,
  COALESCE((SELECT array_agg(g.id ORDER BY g.name)
            FROM movie_genres mg JOIN genres g ON g.id = mg.genre_id
            WHERE mg.movie_id = m.id), ARRAY[]::INTEGER[]) AS genre_ids,
  COALESCE((SELECT array_agg(g.name ORDER BY g.name)
            FROM movie_genres mg JOIN genres g ON g.id = mg.genre_id
            WHERE mg.movie_id = m.id), ARRAY[]::VARCHAR[]) AS genre_names,
  COALESCE((SELECT array_agg(d.id ORDER BY d.name)
            FROM movie_directors md JOIN directors d ON d.id = md.director_id
            WHERE md.movie_id = m.id), ARRAY[]::INTEGER[]) AS director_ids,
  COALESCE((SELECT array_agg(d.name ORDER BY d.name)
            FROM movie_directors md JOIN directors d ON d.id = md.director_id
            WHERE md.movie_id = m.id), ARRAY[]::VARCHAR[]) AS director_names, m.backdrop_path
FROM movies m;